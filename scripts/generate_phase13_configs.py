def _cohort_entry(name: str) -> dict:
    """One input carried VERBATIM from the shipped cohort config -- same
    path, same verified hash. The stop-2 config already resolved the
    shakedown run directory and the ladder inputs, so stop 3 inherits
    them rather than re-declaring a second copy to drift."""
    shipped = REPO / "configs" / COHORT_NAME
    if shipped.is_file():
        payload = yaml.safe_load(shipped.read_text(encoding="utf-8")) or {}
        for entry in payload.get("inputs") or []:
            if entry.get("name") == name:
                return dict(entry)
    return {"name": name, "path": f"PENDING_{name}", "rollup_sha256": PLACEHOLDER}


def _cohort_flag() -> bool:
    """the maintainer's acknowledgement, carried from the shipped cohort config.

    Stop 3's regenerating tasks inherit the SAME decision rather than
    asking for a second edit of the same judgement: generating cohort
    reconstructions was acknowledged, and regenerating them in memory is
    that act (phase13.CLEFT_RECONSTRUCTION_GATE)."""
    return _carried_cohort_flag()


def _scoresheet_entry() -> dict:
    """The primary score sheet, carried verbatim from the shipped IEM
    config -- the same sheet whose Median column Phase 11 trained on."""
    for entry in source(IEM_CONFIG)["inputs"]:
        if entry["name"] == "scoresheet_primary":
            return dict(entry)
    raise SystemExit("p11_iem_arm.yaml declares no scoresheet_primary")


def _carried_named_entry(config_name: str, input_name: str) -> dict | None:
    """An entry the shipped config has already resolved, by name -- the
    three-state carry: a resolved PATH survives regeneration even while
    its hash is a placeholder, a PENDING path never does."""
    path = REPO / "configs" / config_name
    if not path.is_file():
        return None
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    for entry in payload.get("inputs") or []:
        if entry.get("name") == input_name and (
            "/PENDING_" not in str(entry.get("path", ""))
        ):
            return dict(entry)
    return None


def _cohort_run_entry(config_name: str) -> dict:
    return _carried_named_entry(config_name, "cohort_run") or {
        "name": "cohort_run",
        "path": COHORT_RUN_PENDING,
        "rollup_sha256": PLACEHOLDER,
    }


def _provenance(inputs: list) -> str:
    pending = sum(1 for e in inputs if "/PENDING_" in e["path"])
    unresolved = sum(
        1 for e in inputs if set(e["rollup_sha256"]) == {"0"}
    )
    if pending:
        return (
            f"# **{pending} PATH(S) PENDING and {unresolved} ALL-ZERO\n"
            "# PLACEHOLDER HASH(ES).** A run directory carries a SHA and\n"
            "# a job id, neither derivable on a laptop. Two passes: paste\n"
            "# the run directory (path), then declare_inputs.py (hash).\n"
            "# Guard 3 refuses until both are real -- the PLACEHOLDER\n"
            "# working, not a mistake.\n"
        )
    if unresolved:
        return (
            f"# **PATHS RESOLVED, {unresolved} ALL-ZERO PLACEHOLDER\n"
            "# HASH(ES) REMAIN.** Every path is real; declare_inputs.py\n"
            "# fills the rest and guard 3 refuses until it does.\n"
        )
    return (
        "# **RESOLVED.** Every input declared at a real path with a\n"
        "# verified hash.\n"
    )


