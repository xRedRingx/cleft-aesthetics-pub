def _carried_cohort_flag(path=None) -> bool:
    """the maintainer's acknowledgement, carried from the shipped config.

    A fresh render writes ``false``; only an existing ``true`` in the
    shipped config survives regeneration -- the basal three-state carry,
    so the flag can become true ONLY by a deliberate edit, which keeps
    ``--check`` clean (phase13.CLEFT_RECONSTRUCTION_GATE)."""
    path = path or REPO / "configs" / COHORT_NAME
    if not path.is_file():
        return False
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return (
        payload.get("task", {}).get("cleft_reconstruction_acknowledged")
        is True
    )


def _carried_decoder_run(path=None) -> dict:
    """The shakedown run-dir input, three-state: a fresh render writes
    the PENDING path with a placeholder hash; a pasted real path
    survives regeneration even while its hash is still a placeholder;
    a declared hash rides with it thereafter."""
    path = path or REPO / "configs" / COHORT_NAME
    pending = {
        "name": "decoder_run",
        "path": DECODER_RUN_PENDING,
        "rollup_sha256": PLACEHOLDER,
    }
    if not path.is_file():
        return pending
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    for entry in payload.get("inputs") or []:
        if entry.get("name") == "decoder_run" and (
            "/PENDING_" not in str(entry.get("path", ""))
        ):
            return dict(entry)
    return pending


