def source(name: str) -> dict:
    return yaml.safe_load((REPO / "configs" / name).read_text(encoding="utf-8"))


def _carried_hash(config_name: str, input_name: str, path: str) -> str:
    shipped = REPO / "configs" / config_name
    if not shipped.is_file():
        return PLACEHOLDER
    payload = yaml.safe_load(shipped.read_text(encoding="utf-8")) or {}
    for entry in payload.get("inputs") or []:
        if entry.get("name") == input_name and entry.get("path") == path:
            rollup = str(entry.get("rollup_sha256") or "")
            if len(rollup) == 64 and set(rollup) != {"0"}:
                return rollup
    return PLACEHOLDER


def _scut_inputs() -> list[dict]:
    """masked_scut and scut_root, carried verbatim from the pretraining
    config -- same paths, same verified hashes."""
    pretrain = {e["name"]: e for e in source(PRETRAIN_CONFIG)["inputs"]}
    return [dict(pretrain["masked_scut"]), dict(pretrain["scut_root"])]


