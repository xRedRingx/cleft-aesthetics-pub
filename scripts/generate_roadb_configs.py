"""Write Road B Phase 2's configs from ``cleft.roadb``.

    PYTHONPATH=src python scripts/generate_roadb_configs.py [--check]

Ten staging configs, one per setting, plus the residual gate. **The setting
list is not in any config** -- ``roadb.staging_settings()`` derives it, so a
config cannot add a cell the axis does not contain.

Inputs are copied from Road A's Phase 2 config rather than retyped: the same
manifest and the same source folders, so "same sources" is true by
construction rather than by proofreading.
"""

