PLACEHOLDER = "0" * 64


def shared_inputs() -> list[dict]:
    payload = yaml.safe_load(
        (REPO / "configs" / SOURCE_CONFIG).read_text(encoding="utf-8")
    )
    by_name = {entry["name"]: entry for entry in payload["inputs"]}
    missing = [name for name in SHARED_INPUTS if name not in by_name]
    if missing:
        raise SystemExit(f"{SOURCE_CONFIG} no longer declares {missing}")
    return [dict(by_name[name]) for name in SHARED_INPUTS]


def existing(stem: str) -> dict:
    """Resolved entries only -- a placeholder is re-derivable by definition."""
    path = REPO / "configs" / f"{stem}.yaml"
    if not path.is_file():
        return {}
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {
        entry["name"]: entry
        for entry in payload.get("inputs", [])
        if entry.get("rollup_sha256") != PLACEHOLDER
    }


def existing_entries(stem: str) -> dict:
    """Entries with ANYTHING filled -- a resolved hash OR a resolved path.

    ``existing`` carries only resolved hashes, which is right when the path
    is known from the start and the hash arrives later. Where the PATH
    arrives first (a run directory pasted before its declare pass), that
    rule would discard the fill on the next regeneration.
    """
    path = REPO / "configs" / f"{stem}.yaml"
    if not path.is_file():
        return {}
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {
        entry["name"]: entry
        for entry in payload.get("inputs", [])
        if entry.get("rollup_sha256") != PLACEHOLDER
        or "/PENDING_" not in entry.get("path", "")
    }


