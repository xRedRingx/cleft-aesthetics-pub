#: Each Road B arm mirrors ONE Road A ladder arm at G1 -- the harness and
#: regime hyperparameters ride through VERBATIM; only identity fields
#: (backbone, init, artifacts, seeds by regime) are overridden. All
#: counterparts are already at G1, so no geometry override exists anywhere.
#: GRAPH counterparts are PER BACKBONE: agnet arms carry a field srgnn's
#: never do (`deterministic: false` -- the measured roi_align bound,
#: declared rather than defaulted, schema-enforced), so copying srgnn's
#: task for an agnet arm ships an invalid config. The schema caught
#: exactly that on the first generation.
ROAD_A_ARM_COUNTERPARTS = {
    ("transformer", "imagenet"): "p7_d1_vit_b16_imagenet_g1",
    ("transformer", "scut_masked"): "p7_c_swin_b_scut_masked_g1",
    ("srgnn", "imagenet"): "p7_d1_srgnn_imagenet_g1_native",
    ("srgnn", "scut_masked"): "p7_d1_srgnn_scut_masked_g1_native",
    ("agnet", "imagenet"): "p7_d1_agnet_imagenet_g1_native",
    ("agnet", "scut_masked"): "p7_d1_agnet_scut_masked_g1_native",
}


def _counterpart_key(arm: dict) -> tuple[str, str]:
    kind = arm["backbone"] if arm["regime"] == "graph" else "transformer"
    return kind, arm["init"]

SWEEP_STEM = "roadb_p7_graph_seed_band"


def _arm_stem(arm: dict) -> str:
    short = "imagenet" if arm["init"] == "imagenet" else "masked"
    return f"roadb_p7_arm_{arm['backbone']}_{short}_{arm['resolution']}"


def _arm_payload(
    arm: dict, stem: str, fallback_stem: str | None = None
) -> tuple[dict, dict]:
    """One arm's payload -- also the sweep's, for the band cell, which is
    how "task block identical by construction" is construction rather
    than proofreading. Returns (payload, state) where state carries what
    the header needs to say."""
    from cleft import embedding_plan, ladder

    backbone, resolution = arm["backbone"], arm["resolution"]
    init, regime = arm["init"], arm["regime"]
    counterpart = ROAD_A_ARM_COUNTERPARTS[_counterpart_key(arm)]
    source = yaml.safe_load(
        (REPO / "configs" / f"{counterpart}.yaml").read_text(encoding="utf-8")
    )
    task = dict(source["task"])
    staged_name, staged_hash = STAGED_FOR_EXTRACTION[resolution]
    task["backbone"] = backbone
    task["init"] = init
    task["staged_artifact"] = staged_name
    task["seeds"] = list(ladder.SEED_POOL[: arm["seeds"]])

    inputs = [
        {"name": "manifest_v1",
         "path": f"{CLUSTER_ROOT}/data/manifests/cleft_v1",
         "rollup_sha256": MANIFEST_HASH},
        {"name": staged_name,
         "path": f"{CLUSTER_ROOT}/data/staged/{staged_name}",
         "rollup_sha256": staged_hash},
    ]
    state = {"counterpart": counterpart}

    if "bitwise reuse" in arm["set_artifact"]:
        # The counterpart IS Road A's swin masked-G1 224 arm, so its own
        # entries are the reuse entries -- copied verbatim, "same bytes"
        # by construction.
        road_a = {e["name"]: e for e in source["inputs"]}
        emb_entry = dict(road_a["embeddings"])
        ckpt_entry = dict(road_a["ckpt_swin_b_masked_g1"])
        inputs += [emb_entry, ckpt_entry]
        task["checkpoint"] = ckpt_entry["name"]
        state.update(reuse=True, emb_placeholder=False, ckpt_state="resolved")
        payload = {
            "schema_version": 1, "phase": "roadb_p7", "tier": "keeper",
            "seed": 1337, "inputs": inputs, "task": task,
        }
        return payload, state

    scheme = "native" if regime == "graph" and init != "imagenet" else None
    set_dir = embedding_plan.set_name({
        "backbone": backbone, "init": init, "geometry": "g1",
        "pretrain_scheme": scheme,
    })
    carried = existing(stem).get("embeddings")
    if not carried and fallback_stem:
        carried = existing(fallback_stem).get("embeddings")
    emb_entry = carried or {
        "name": "embeddings",
        "path": (
            f"{CLUSTER_ROOT}/data/embeddings/{arm['set_artifact']}/{set_dir}"
        ),
        "rollup_sha256": PLACEHOLDER,
    }
    inputs.append(emb_entry)
    state.update(
        reuse=False,
        emb_placeholder=emb_entry["rollup_sha256"] == PLACEHOLDER,
        ckpt_state=None,
    )

    if init != "imagenet":
        # The paired checkpoint, copied VERBATIM from the extraction
        # config -- the run refuses a mismatch between the set's recorded
        # checkpoint and the declared one, and copying is how the two
        # configs cannot disagree. Placeholder states mirror through.
        ex_stem = f"roadb_p7_extract_{backbone}_masked_{resolution}"
        ex_payload = yaml.safe_load(
            (REPO / "configs" / f"{ex_stem}.yaml").read_text(encoding="utf-8")
        )
        ckpts = [
            e for e in ex_payload["inputs"] if e["name"].startswith("ckpt_")
        ]
        if len(ckpts) != 1:
            raise SystemExit(f"{ex_stem} declares {len(ckpts)} checkpoints")
        ckpt_entry = dict(ckpts[0])
        inputs.append(ckpt_entry)
        task["checkpoint"] = ckpt_entry["name"]
        state["ckpt_state"] = (
            "placeholder" if ckpt_entry["rollup_sha256"] == PLACEHOLDER
            else "resolved"
        )

    payload = {
        "schema_version": 1, "phase": "roadb_p7", "tier": "keeper",
        "seed": 1337, "inputs": inputs, "task": task,
    }
    return payload, state


