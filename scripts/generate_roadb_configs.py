def artifact_inputs(stem: str) -> tuple[list[dict], int]:
    """The ten artifact declarations for a config that reads all ten.

    Resolved hashes are carried from this config's own file first, then from
    the gate's -- the sheets and the verdict must describe the SAME bytes,
    so re-pasting hashes independently would be a place for them to diverge.
    """
    carried = existing(stem)
    fallback = existing("roadb_p2_residual_gate") if stem != "roadb_p2_residual_gate" else {}
    inputs = []
    for setting in roadb.staging_settings():
        name = setting["artifact"]
        inputs.append(carried.get(name) or fallback.get(name) or {
            "name": name,
            "path": f"{CLUSTER_ROOT}/data/staged/{name}",
            "rollup_sha256": PLACEHOLDER,
        })
    unresolved = sum(1 for e in inputs if e["rollup_sha256"] == PLACEHOLDER)
    return inputs, unresolved


