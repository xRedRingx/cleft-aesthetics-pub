def _known_hashes_by_path() -> dict:
    """Every verified hash any shipped config already declares, by path --
    the paired generator's reuse rule: one path, one hash, no second
    cluster round trip for a file already declared."""
    known: dict[str, str] = {}
    for path in sorted((REPO / "configs").glob("*.yaml")):
        payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        for entry in payload.get("inputs") or []:
            rollup = entry.get("rollup_sha256")
            if rollup and set(str(rollup)) != {"0"} and "*" not in entry["path"]:
                known.setdefault(entry["path"], str(rollup))
    return known


