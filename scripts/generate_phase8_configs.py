PLACEHOLDER = "0" * 64


def _carried(config_name: str, input_name: str, expected_path: str) -> str:
    """A resolved hash CARRIED from the shipped config while the path still
    matches -- the generate_phase7d_configs rule, needed here once 8c's
    inputs started resolving in passes."""
    path = REPO / "configs" / config_name
    if not path.is_file():
        return PLACEHOLDER
    payload = yaml.safe_load(path.read_text(encoding="utf-8"))
    for entry in payload.get("inputs") or []:
        if entry.get("name") != input_name:
            continue
        rollup = str(entry.get("rollup_sha256") or "")
        if (
            entry.get("path") == expected_path
            and len(rollup) == 64
            and set(rollup) <= set("0123456789abcdef")
            and set(rollup) != {"0"}
        ):
            return rollup
    return PLACEHOLDER


