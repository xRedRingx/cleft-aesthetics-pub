def carried_control_rollup() -> str | None:
    """The control's VERIFIED hash, carried from the shipped config.

    Hashes come only from declare_inputs.py against the built artifact
    (guard 3 re-verifies before any run starts), so this generator cannot
    produce one -- it can only CARRY what the declare pass filled in, and
    only while the path it was declared against is still the path derived
    here. A rename invalidates the carry and the entry reverts to the
    placeholder, exactly as generate_roadb_configs' existing_entries()
    decided after a stale path rode through a rename once.
    """
    path = REPO / "configs" / "p8_node_weights.yaml"
    if not path.is_file():
        return None
    payload = yaml.safe_load(path.read_text(encoding="utf-8"))
    for entry in payload.get("inputs") or []:
        if entry.get("name") != CONTROL_INPUT:
            continue
        rollup = str(entry.get("rollup_sha256") or "")
        if (
            entry.get("path") == control_path()
            and len(rollup) == 64
            and set(rollup) <= set("0123456789abcdef")
            and set(rollup) != {"0"}
        ):
            return rollup
    return None


