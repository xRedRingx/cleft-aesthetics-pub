PAIRED_NAME = "p12_paired.yaml"


def _carried_paired_entries() -> dict:
    """Entries the paired config has already resolved, by name -- the
    three-state carry: a resolved PATH survives regeneration even while
    its hash is still a placeholder, a PENDING path never does."""
    path = REPO / "configs" / PAIRED_NAME
    if not path.is_file():
        return {}
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {
        e["name"]: e for e in payload.get("inputs") or []
        if "/PENDING_" not in e["path"]
    }


