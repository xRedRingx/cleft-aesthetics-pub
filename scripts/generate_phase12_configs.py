def _carried_flag(path=None) -> bool:
    """the maintainer's acknowledgement, carried from the shipped config.

    A fresh render writes ``false``; only an existing ``true`` in the
    shipped config survives regeneration -- the same three-state carry as
    a filled hash, so the flag can become true ONLY by a deliberate edit
    edit keeps ``--check`` clean (``phase12.BASAL_USE_GATE``)."""
    path = path or REPO / "configs" / STAGE_NAME
    if not path.is_file():
        return False
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return payload.get("task", {}).get("basal_use_acknowledged") is True


def _carried_views_hash(path=None) -> str:
    """The views manifest's rollup, carried once declare_inputs fills it.

    The artifact was built by stop 1 on the cluster; its hash is not
    derivable on a laptop, so a fresh render writes the documented
    placeholder and the declare pass fills it -- carried thereafter."""
    path = path or REPO / "configs" / STAGE_NAME
    if not path.is_file():
        return PLACEHOLDER
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    for entry in payload.get("inputs") or []:
        if (
            entry.get("name") == "manifest_views"
            and entry.get("path") == VIEWS_MANIFEST_PATH
        ):
            rollup = str(entry.get("rollup_sha256") or "")
            if len(rollup) == 64 and set(rollup) != {"0"}:
                return rollup
    return PLACEHOLDER


