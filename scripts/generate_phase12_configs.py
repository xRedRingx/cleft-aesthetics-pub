def render_arm(name: str) -> str:
    arm_key, channels, head_parameters = ARMS[name]
    source_arm = source(SOURCE_CONFIG)
    arm_task = source_arm["task"]
    ladder_inputs = {e["name"]: e for e in source_arm["inputs"]}

    inputs = [_views_manifest_input()]
    task = {
        "kind": "view_arm",
        "arm": arm_key,
        "views": channels,
        "manifest_artifact": "manifest_views",
    }
    if "frontal" in channels:
        inputs.append(dict(ladder_inputs["embeddings"]))
        task["frontal_embeddings"] = "embeddings"
    if "basal" in channels:
        inputs.append({
            "name": "basal_embeddings",
            "path": BASAL_EMBEDDINGS_PATH,
            "rollup_sha256": _carried_hash(
                name, "basal_embeddings", BASAL_EMBEDDINGS_PATH
            ),
        })
        task["basal_embeddings"] = "basal_embeddings"
    # The RECIPE is copied from the 0.2520 arm's shipped config, so
    # recipe identity is by construction rather than by transcription.
    task.update({
        "label": arm_task["label"],
        "seeds": arm_task["seeds"],
        "inner_val_frac": arm_task["inner_val_frac"],
        "max_epochs": arm_task["max_epochs"],
        "patience": arm_task["patience"],
        "monitor": arm_task["monitor"],
        "learning_rate": arm_task["learning_rate"],
        "weight_decay": arm_task["weight_decay"],
        "expect_patients": views.VIEWS_COHORT["patients"],
        "expect_head_parameters": head_parameters,
    })
    payload = {
        "schema_version": 1,
        "phase": "p12",
        "tier": "keeper",
        "seed": arm_task["seeds"][0],
        "inputs": inputs,
        "task": task,
    }
    unresolved = sum(
        1 for e in inputs if set(e["rollup_sha256"]) == {"0"}
    )
    body = yaml.safe_dump(payload, sort_keys=False, default_flow_style=False)
