PAIRED_NAME = "p10_paired.yaml"
PLACEHOLDER = "0" * 64


def _carried_vectors() -> dict:
    """Entries ``p10_paired.yaml`` has already resolved, by name.

    Three-state, the standing shape: a resolved PATH is carried even when
    its hash is still a placeholder, because the two resolve in separate
    passes and the path is the half that cannot be re-derived here. A
    PENDING path is never carried -- it IS the re-derivable state.
    """
    path = REPO / "configs" / PAIRED_NAME
    if not path.is_file():
        return {}
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {
        entry["name"]: entry
        for entry in payload.get("inputs") or []
        if "/PENDING_" not in entry["path"]
    }


def _known_hashes() -> dict:
    """Every prediction vector any shipped config already declares, by
    path. A path's contents are immutable, so one verified hash serves
    every config declaring it -- which is what makes the 0.2520 arm's
    five vectors need no cluster round trip at all."""
    known: dict[str, str] = {}
    for path in sorted((REPO / "configs").glob("*.yaml")):
        payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        for entry in payload.get("inputs") or []:
            rollup = entry.get("rollup_sha256") or ""
            if (
                len(rollup) == 64 and set(rollup) != {"0"}
                and entry["path"].endswith("__predictions.csv")
            ):
                known.setdefault(entry["path"], rollup)
    return known


def render_paired() -> str:
    """PLAN 4.3 condition 1 for the replication against the 0.2520 arm.

    Same task, same BCa, same loader as Road A's and Road B's scopes --
    only the pair enumeration differs, and it is derived in
    ``phase10.paired_claim_pairs``. The Road B precedent, applied rather
    than re-implemented.
    """
    from cleft import ladder

    pairs = phase10.paired_claim_pairs("p10")
    vectors = ladder.paired_claim_vectors("p10", pairs=pairs)
    stems = ladder.paired_claim_stems("p10", pairs=pairs)
    carried = _carried_vectors()
    known = _known_hashes()
    # A stem another config already resolved: reuse its run directory's
    # full prefix so the path matches byte for byte and the hash carries.
    resolved_prefix = {}
    for path in known:
        directory = path.rpartition("/")[0]
        run_dir = directory.rpartition("/")[2]
        resolved_prefix.setdefault(run_dir.split("__")[0], directory)

    inputs = []
    for stem, seed in vectors:
        name = f"oof_{stem}_seed_{seed}"
        if name in carried:
            inputs.append(carried[name])
            continue
        if stem in resolved_prefix:
            path = f"{resolved_prefix[stem]}/seed_{seed}__predictions.csv"
        else:
            # PENDING, not a glob: a glob wears the run-directory SHAPE
            # the mistyped-launch sweep checks, and would be rejected as a
            # sha. PENDING_<stem> has no `__` and stays outside it.
            path = (
                f"{CLUSTER_ROOT}/runs/keeper/p10/PENDING_{stem}/"
                f"seed_{seed}__predictions.csv"
            )
        inputs.append({
            "name": name, "path": path,
            "rollup_sha256": known.get(path, PLACEHOLDER),
        })

    unresolved = sum(1 for e in inputs if e["rollup_sha256"] == PLACEHOLDER)
    pending = sum(1 for e in inputs if "/PENDING_" in e["path"])
    spec = phase10.PHASE_10_PAIRED_REGISTERED
