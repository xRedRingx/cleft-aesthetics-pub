def _carried(config_name: str, input_name: str, path: str) -> str:
    """A verified hash carried from a shipped config while its path still
    matches -- the standing two-pass carry."""
    shipped = REPO / "configs" / config_name
    if not shipped.is_file():
        return "0" * 64
    payload = yaml.safe_load(shipped.read_text(encoding="utf-8"))
    for entry in payload.get("inputs") or []:
        if entry.get("name") == input_name and entry.get("path") == path:
            rollup = str(entry.get("rollup_sha256") or "")
            if len(rollup) == 64 and set(rollup) != {"0"}:
                return rollup
    return "0" * 64


