        "# 0.2520 ARM. The phase's FOURTH EXIT CRITERION and its LAST\n"
        "# OUTSTANDING RUN. phase10.PHASE_10_PAIRED_REGISTERED.\n"
        "#\n"
        "# GENERATED by scripts/generate_phase10_configs.py from\n"
        "# phase10.paired_claim_pairs('p10').\n"
        "#\n"
        "# **THIS RUN FITS NOTHING.** Every vector it reads was written by\n"
