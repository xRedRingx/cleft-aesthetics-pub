DEALL_SET_PATH = "${CLEFT_ANCHOR_SET}"
DEALL_INPUT = "deall_set"


def _deall_entry() -> dict:
    rollup = PLACEHOLDER
    shipped = REPO / "configs" / "p9_deall_reference.yaml"
    if shipped.is_file():
        payload = yaml.safe_load(shipped.read_text(encoding="utf-8"))
        for entry in payload.get("inputs") or []:
            if entry.get("name") != DEALL_INPUT:
                continue
            carried = str(entry.get("rollup_sha256") or "")
            if (
                entry.get("path") == DEALL_SET_PATH
                and len(carried) == 64
                and set(carried) <= set("0123456789abcdef")
                and set(carried) != {"0"}
            ):
                rollup = carried
    return {
        "name": DEALL_INPUT,
        "path": DEALL_SET_PATH,
        "rollup_sha256": rollup,
    }


