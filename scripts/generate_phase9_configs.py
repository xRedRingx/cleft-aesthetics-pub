def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    drifted = 0
    for name, builder in CONFIGS.items():
        path = REPO / "configs" / name
        text = builder()
        if args.check:
            if not path.is_file():
                print(f"  DRIFT {name}: missing")
                drifted += 1
            elif path.read_text(encoding="utf-8") != text:
                print(f"  DRIFT {name}: differs from the derived config")
                drifted += 1
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {name}")
    if args.check:
        print(f"{len(CONFIGS)} configs checked, {drifted} drifted")
        return 1 if drifted else 0
    print(
        f"prototypes and deall-reference inputs carried from "
        f"{SOURCE_CONFIG}; deall_set path filled, hash "
        + ("PLACEHOLDER pending the declare pass"
           if set(_deall_entry()["rollup_sha256"]) == {"0"}
           else "filled and carried")
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
